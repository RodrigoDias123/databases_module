-- [x] Each query preceded by the question it answers

--query 1: What are the top 5 most rented films?

Select f.film_id, f.title, count(r.rental_id) as rental_count
From rental r
Join inventory i on r.inventory_id = i.inventory_id
Join film f on i.film_id = f.film_id
Group by f.film_id
Order by rental_count desc
Limit 5;

--query 2: Which customers have rented the most films?

Select c.first_name, c.last_name, count(r.rental_id) as rental_count
From rental r
Join customer c on r.customer_id = c.customer_id
Group by c.customer_id
Order by rental_count desc
Limit 5;

--query 3: What is the total revenue generated by each film?

Select f.film_id, f.title, sum(p.amount) as total_revenue
From payment p
Join rental r on p.rental_id = r.rental_id
Join inventory i on r.inventory_id = i.inventory_id
Join film f on i.film_id = f.film_id
Group by f.film_id
Order by total_revenue desc;

--query 4: Which films have never been rented?

Select f.title
From film f
Left Join inventory i on f.film_id = i.film_id
Left Join rental r on i.inventory_id = r.inventory_id
Where r.rental_id is null
Order by f.title;

--query 5: What is the average actual rental duration (in days) for each film?

Select f.film_id, f.title, f.rental_duration as allowed_days,
       round(avg(extract(epoch from r.return_date - r.rental_date) / 86400), 2) as avg_actual_days,
       count(r.rental_id) as rentals
From film f
Join inventory i on i.film_id = f.film_id
Join rental r on r.inventory_id = i.inventory_id
Where r.return_date is not null
Group by f.film_id
Order by avg_actual_days desc;

--query 6: Which actors have appeared in the most films?

Select a.first_name, a.last_name, count(fa.film_id) as film_count
From actor a
Join film_actor fa on a.actor_id = fa.actor_id
Group by a.actor_id
Order by film_count desc
Limit 5;

--query 7: What is the total number of rentals per month?

select date_trunc('month', r.rental_date) as rental_month, count(r.rental_id) as rental_count
from rental r
group by rental_month
order by rental_month;

--query 8: Which customers have spent the most money on rentals?

select c.first_name, c.last_name, sum(p.amount) as total_spent
from payment p
join customer c on p.customer_id = c.customer_id
group by c.customer_id
order by total_spent desc
limit 5;

--query 9: What is the most popular film category based on rentals?

With category_rentals as (
    Select c.category_id, c.name as category_name, count(r.rental_id) as rental_count
    From rental r
    Join inventory i on r.inventory_id = i.inventory_id
    Join film_category fc on i.film_id = fc.film_id
    Join category c on fc.category_id = c.category_id
    Group by c.category_id
)
Select category_name, rental_count
From category_rentals
Where rental_count = (Select max(rental_count) From category_rentals);

--query 10: Which pairs of actors have appeared in more than 3 films together?

Select a1.first_name || ' ' || a1.last_name as actor_1,
       a2.first_name || ' ' || a2.last_name as actor_2,
       count(*) as films_together
From film_actor fa1
Join film_actor fa2 on fa2.film_id = fa1.film_id
                   and fa2.actor_id > fa1.actor_id
Join actor a1 on a1.actor_id = fa1.actor_id
Join actor a2 on a2.actor_id = fa2.actor_id
Group by a1.actor_id, a2.actor_id
Having count(*) > 3
Order by films_together desc, actor_1, actor_2;
